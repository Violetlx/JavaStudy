package com.leetcode.medium.domain;

/**
 * 两数相加链表
 *
 * @author lixuan
 * @Date 2025/4/16 11:27
 */
public class ListNode {
    public int val;
    public ListNode next;
    public ListNode() {}
    public ListNode(int val) { this.val = val; }
    public ListNode(int val, ListNode next) { this.val = val; this.next = next;}
}
